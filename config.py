from __future__ import annotations

import json
from copy import deepcopy
from pathlib import Path
from typing import Any


# ============================================================
# Default configuration
# ============================================================

DEFAULT_CONFIG = {
    "version": 2,
    "name": "",
    "description": "",
    "criteria": [],
}


def empty_config() -> dict[str, Any]:
    """
    Return a fresh empty evaluator configuration.

    deepcopy() is used so that changes to the returned dictionary
    never modify DEFAULT_CONFIG itself.
    """

    return deepcopy(DEFAULT_CONFIG)


# ============================================================
# Validation
# ============================================================

SUPPORTED_RULE_TYPES = {
    "entity",
    "relation",
    "layout",
    "file",
}

SUPPORTED_ENTITIES = {
    "circle",
    "line",
    "polyline",
    "dimension",
    "hatch",
    "text",
    "block",
}

SUPPORTED_RELATIONS = {
    "x_distance",
    "y_distance",
    "distance_2d",
    "same_x",
    "same_y",
}

SUPPORTED_COUNT_OPERATORS = {
    "equals",
    "greater_or_equal",
    "less_or_equal",
}


def validate_config(config: dict[str, Any],) -> list[str]:
    """
    Validate the general structure of an evaluator configuration.

    Returns
    -------
    list[str]
        Empty list if valid, otherwise a list of validation errors.

    Notes
    -----
    This performs structural validation.

    More detailed checks of properties/operators generated by the LLM
    are handled by criteria_generator.py.
    """

    errors: list[str] = []
    if not isinstance(config, dict):
        return ["De configuratie moet een JSON-object zijn."]

    # --------------------------------------------------------
    # Version
    # --------------------------------------------------------

    version = config.get("version")
    if version is None:
        errors.append("De configuratie bevat geen 'version'.")
    elif not isinstance(version, int):
        errors.append("'version' moet een integer zijn.")

    # --------------------------------------------------------
    # Name
    # --------------------------------------------------------

    name = config.get("name")
    if name is not None and not isinstance(name, str):
        errors.append("'name' moet tekst zijn.")

    # --------------------------------------------------------
    # Description
    # --------------------------------------------------------

    description = config.get("description")
    if (description is not None and not isinstance(description, str)):
        errors.append("'description' moet tekst zijn.")

    # --------------------------------------------------------
    # Criteria
    # --------------------------------------------------------

    criteria = config.get("criteria")
    if criteria is None:
        errors.append("De configuratie bevat geen 'criteria'-lijst.")
        return errors
    if not isinstance(criteria, list):
        errors.append("'criteria' moet een lijst zijn.")
        return errors

    # --------------------------------------------------------
    # Rule IDs must be unique
    # --------------------------------------------------------

    seen_ids: set[str] = set()

    for index, rule in enumerate(criteria, start=1):
        prefix = f"Criterium {index}"
        if not isinstance(rule, dict):
            errors.append(f"{prefix}: criterium moet een JSON-object zijn.")
            continue

        # ----------------------------------------------------
        # ID
        # ----------------------------------------------------

        rule_id = rule.get("id")
        if not rule_id:
            errors.append(f"{prefix}: geen 'id' opgegeven.")
        elif not isinstance(rule_id, str):
            errors.append(f"{prefix}: 'id' moet tekst zijn.")
        elif rule_id in seen_ids:
            errors.append(f"{prefix}: dubbele id '{rule_id}'.")
        else:
            seen_ids.add(rule_id)

        # ----------------------------------------------------
        # Name
        # ----------------------------------------------------

        rule_name = rule.get("name")
        if not rule_name:
            errors.append(f"{prefix}: geen naam opgegeven.")

        # ----------------------------------------------------
        # Enabled
        # ----------------------------------------------------

        enabled = rule.get("enabled", True)
        if not isinstance(enabled, bool):
            errors.append(f"{prefix}: 'enabled' moet true of false zijn.")

        # ----------------------------------------------------
        # Points
        # ----------------------------------------------------

        points = rule.get("points", 1.0)
        if not isinstance(points, (int, float)):
            errors.append(f"{prefix}: 'points' moet numeriek zijn.")
        elif points < 0:
            errors.append(f"{prefix}: 'points' mag niet negatief zijn.")

        # ----------------------------------------------------
        # Rule type
        # ----------------------------------------------------

        rule_type = rule.get("type")
        if rule_type not in (SUPPORTED_RULE_TYPES):
            errors.append(f"{prefix}: niet-ondersteund rule type '{rule_type}'.")
            continue

        # ====================================================
        # ENTITY RULE
        # ====================================================

        if rule_type == "entity":
            entity = rule.get("entity")
            if entity not in (SUPPORTED_ENTITIES):
                errors.append(f"{prefix}: niet-ondersteunde entity '{entity}'.")

            conditions = rule.get("conditions")
            if not isinstance(conditions, list):
                errors.append(f"{prefix}: 'conditions' moet een lijst zijn.")
            elif len(conditions) == 0:
                errors.append(f"{prefix}: minstens één condition is vereist.")

            else:
                for condition_index, condition in enumerate(conditions, start=1):
                    condition_prefix = (f"{prefix}, voorwaarde {condition_index}")
                    if not isinstance(condition, dict):
                        errors.append(f"{condition_prefix}: moet een object zijn.")
                        continue
                    if not condition.get("property"):
                        errors.append(f"{condition_prefix}: geen property opgegeven.")
                    if not condition.get("operator"):
                        errors.append(f"{condition_prefix}: geen operator opgegeven.")
                    if "value" not in condition:
                        errors.append(f"{condition_prefix}: geen value opgegeven.")

                    tolerance = (condition.get("tolerance", 0))
                    if not isinstance(tolerance, (int, float)):
                        errors.append(f"{condition_prefix}: tolerance moet numeriek zijn.")
                    elif tolerance < 0:
                        errors.append(f"{condition_prefix}: tolerance mag niet negatief zijn.")

            count_operator = rule.get("count_operator", "greater_or_equal")
            if (count_operator not in SUPPORTED_COUNT_OPERATORS):
                errors.append(f"{prefix}: niet-ondersteunde count_operator '{count_operator}'.")

            count = rule.get("count", 1)
            if not isinstance(count, int):
                errors.append(f"{prefix}: 'count' moet een integer zijn.")
            elif count < 0:
                errors.append(f"{prefix}: 'count' mag niet negatief zijn.")

        # ====================================================
        # RELATION RULE
        # ====================================================

        elif rule_type == "relation":
            entity = rule.get("entity")
            if entity not in (SUPPORTED_ENTITIES):
                errors.append(f"{prefix}: niet-ondersteunde entity '{entity}'.")

            relation = rule.get("relation")
            if relation not in (SUPPORTED_RELATIONS):
                errors.append(f"{prefix}: niet-ondersteunde relation '{relation}'.")
            if relation not in {"same_x", "same_y"}:
                if "value" not in rule:
                    errors.append(f"{prefix}: relation vereist een 'value'.")

            tolerance = rule.get("tolerance", 0)
            if not isinstance(tolerance, (int, float)):
                errors.append(f"{prefix}: tolerance moet numeriek zijn.")

        # ====================================================
        # LAYOUT RULE
        # ====================================================

        elif rule_type == "layout":
            conditions = rule.get("conditions")
            if not isinstance(conditions, dict):
                errors.append(f"{prefix}: layout conditions moet een object zijn.")
            elif not conditions:
                errors.append(f"{prefix}: minstens één layoutvoorwaarde is vereist.")

        # ====================================================
        # FILE RULE
        # ====================================================

        elif rule_type == "file":
            extension = rule.get("extension")
            if not extension:
                errors.append(f"{prefix}: geen bestandsextensie opgegeven.")
            elif not isinstance(extension, str):
                errors.append(f"{prefix}: extension moet tekst zijn.")

            minimum_count = rule.get("minimum_count", 1)
            if not isinstance(minimum_count, int):
                errors.append(f"{prefix}: minimum_count moet een integer zijn.")

            minimum_size = rule.get("minimum_size", 0)
            if not isinstance(minimum_size, (int, float)):
                errors.append(f"{prefix}: minimum_size moet numeriek zijn.")

    return errors


def assert_valid_config(config: dict[str, Any]) -> None:
    """
    Raise ValueError if a configuration is invalid.
    """

    errors = validate_config(config)
    if errors:
        raise ValueError("Ongeldige configuratie:\n- " + "\n- ".join(errors))


# ============================================================
# Normalisation
# ============================================================

def normalize_config(config: dict[str, Any]) -> dict[str, Any]:
    """
    Fill optional configuration fields with sensible defaults.

    Existing values are preserved.
    """

    result = deepcopy(config)
    result.setdefault("version", 2)
    result.setdefault("name", "")
    result.setdefault("description", "")
    result.setdefault("criteria", [])

    for rule in result["criteria"]:
        if not isinstance(rule, dict):
            continue

        rule.setdefault("enabled", True)
        rule.setdefault("points", 1.0)

        rule_type = rule.get("type")
        if rule_type == "entity":
            rule.setdefault("conditions", [])
            rule.setdefault("count_operator", "greater_or_equal")
            rule.setdefault("count", 1)

            for condition in rule["conditions"]:
                if isinstance(condition, dict):
                    condition.setdefault("tolerance", 0.0)
        elif rule_type == "relation":
            rule.setdefault("tolerance", 0.0)
        elif rule_type == "layout":
            rule.setdefault("conditions", {})
        elif rule_type == "file":
            rule.setdefault("minimum_count", 1)
            rule.setdefault("minimum_size", 0)

    return result


# ============================================================
# JSON conversion
# ============================================================

def config_to_json(config: dict[str, Any], indent: int = 2) -> str:
    """
    Convert configuration to formatted JSON text.
    """

    return json.dumps(config, indent=indent, ensure_ascii=False)


def config_from_json(json_text: str, validate: bool = True) -> dict[str, Any]:
    """
    Parse configuration from JSON text.
    """

    try:
        config = json.loads(json_text)
    except json.JSONDecodeError as exc:
        raise ValueError(f"Het bestand bevat geen geldige JSON:\n{exc}") from exc

    config = normalize_config(config)
    if validate:
        assert_valid_config(config)

    return config


# ============================================================
# File I/O
# ============================================================

def load_config(path: str | Path, validate: bool = True) -> dict[str, Any]:
    """
    Load evaluator configuration from a JSON file.
    """

    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Configuratiebestand bestaat niet: {path}")

    if not path.is_file():
        raise ValueError(f"Pad is geen bestand: {path}")

    text = path.read_text(encoding="utf-8")

    return config_from_json(text, validate=validate)


def save_config(config: dict[str, Any], path: str | Path, validate: bool = True) -> Path:
    """
    Save evaluator configuration to a JSON file.

    Returns the final Path.
    """

    config = normalize_config(config)
    if validate:
        assert_valid_config(config)

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(config_to_json(config), encoding="utf-8")

    return path
